import { readFileSync, writeFileSync, mkdirSync, cpSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { basename, dirname, extname, resolve } from 'node:path';
import { buildSnapshot } from './bootstrap-snapshot.mjs';
import { starterAssignments } from './room-art-starter-assets.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
export const project = resolve(root, 'unity/OrionisRoomArtLab');
export function assetBrowserCatalog() {
  const inventory = JSON.parse(readFileSync(resolve(root, 'docs/room-asset-inventory.json'), 'utf8'));
  const label = value => value.replace(/\.[^.]+$/, '').replace(/^(SM_Gen_Prop_|SM_Gen_|SM_Prop_|SM_)/, '').replaceAll(/[_-]/g, ' ');
  const assets = inventory.assets.flatMap(group => group.sources.map(path => {
    const extension = extname(path).toLowerCase();
    const pack = path.includes('/Synty/') ? path.split('/Synty/')[1].split('/')[0]
      : path.includes('/Assets/') ? path.split('/Assets/')[1].split('/')[0] : 'Orionis';
    const kind = /\/Animations?\/|\/animation\/|\.anim$/i.test(path) ? 'Animation'
      : /\/Characters?\/|\/CaD_vol1\/Prefabs\//i.test(path) ? 'Characters'
      : /\/Base\/|\/Buildings?\//.test(path) ? 'Structure'
      : /\/Environment\/|\/Generic\//.test(path) ? 'Terrain'
      : /\/FX\//.test(path) ? 'Effects' : /\/Icons\//.test(path) ? 'Icons'
      : /\/Primitives\//.test(path) ? 'Blockouts' : 'Props & models';
    return { id: path, path, label: label(basename(path)), pack, kind, disabled: false, image: false, extension };
  }));
  for (const sprite of inventory.sprites) assets.push({ id: 'sprite:' + sprite.key, path: sprite.path,
    label: label(sprite.key), pack: 'Orionis sprites', kind: '2D sprites', disabled: sprite.disabled, image: true, extension: '.png' });
  const targets = inventory.baseRooms.map(r => ({ id: 'base:' + r.id, label: 'Base / ' + r.name }));
  for (const mission of inventory.missions) {
    const missionId = basename(mission.source, '.finalized.json');
    const authored = JSON.parse(readFileSync(resolve(root, mission.source), 'utf8'));
    for (const stage of mission.stages) {
      const cells = authored.stages.find(s => s.stageId === stage.stageId).cells;
      const minX = Math.min(...cells.map(c => c.x)), minY = Math.min(...cells.map(c => c.y));
      targets.push({ id: 'mission:' + missionId + ':' + stage.stageId,
        label: 'Mission / ' + label(missionId) + ' / ' + (stage.playerLabel || label(stage.stageId.replace(/^stage-/, ''))),
        cells: cells.map(c => ({ x: c.x - minX, y: c.y - minY })) });
    }
  }
  return { assets: assets.sort((a, b) => a.pack.localeCompare(b.pack) || a.label.localeCompare(b.label) || a.id.localeCompare(b.id)), targets };
}
export function stagedFiles() {
  const snapshot = buildSnapshot();
  const rulesPath = 'unity/StargateOrionis/Assets/Orionis/Domain/RoomJoinGeometry.cs';
  const rules = readFileSync(resolve(root, rulesPath), 'utf8');
  const catalog = {
    sources: snapshot.sources,
    joinRuleSha256: createHash('sha256').update(rules).digest('hex'),
    rooms: snapshot.roomPlanning.rooms.map(p => ({
      ...snapshot.roomDefinitions.find(r => r.id === p.id), category: p.category,
      joinGroup: p.joinGroup, joinLayouts: p.joinLayouts, tiers: p.tiers.map(t => t.tier),
    })),
  };
  return new Map([
    ['Assets/RoomArtLab/Editor/Generated/room-catalog.json', JSON.stringify(catalog, null, 2) + '\n'],
    ['Assets/RoomArtLab/Editor/Generated/RoomJoinGeometry.cs', '// Generated by unity/tools/room-art-lab.mjs; edit the game source.\n' + rules],
    ['Assets/RoomArtLab/Editor/Generated/asset-browser.json', JSON.stringify(assetBrowserCatalog(), null, 2) + '\n'],
    ['Assets/RoomArtLab/Editor/Generated/starter-assignments.json', JSON.stringify(starterAssignments(assetBrowserCatalog()), null, 2) + '\n'],
  ]);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const command = process.argv[2] ?? 'stage';
  if (command === 'stage-assets') {
    // Copy unchanged local art into this isolated project; no scenes or vendor code.
    for (const pack of ['PolygonGeneric', 'PolygonPrototype']) for (const folder of ['Models', 'Materials', 'Textures', 'Shaders', 'Prefabs']) {
      const source = resolve(root, 'unity/StargateOrionis/Assets/Synty', pack, folder);
      const target = resolve(project, 'Assets/Synty', pack, folder);
      cpSync(source, target, { recursive: true });
      if (existsSync(source + '.meta')) cpSync(source + '.meta', target + '.meta');
    }
    console.log('Staged unchanged Synty models, materials, textures, shaders and prefabs in the Room Art Lab.');
  } else if (['stage', '--check'].includes(command)) {
    for (const [relative, text] of stagedFiles()) {
      const target = resolve(project, relative);
      if (command === '--check') {
        if (readFileSync(target, 'utf8') !== text) throw Error('Stale Room Art Lab input: ' + relative);
      } else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, text); }
    }
    console.log(command === '--check' ? 'Room Art Lab catalog and shared join rule are current.' : 'Staged Room Art Lab catalog and shared join rule.');
  } else {
    const descriptor = JSON.parse(readFileSync(resolve(project, 'Library/Pipeline/.unity-pipeline-port'), 'utf8'));
    const normalize = p => resolve(p).replaceAll('\\', '/').toLowerCase();
    if (normalize(descriptor.projectPath) !== normalize(project)) throw Error('Refusing mismatched Editor descriptor.');
    const code = command === 'open' ? 'Orionis.RoomArtLab.RoomArtLabWindow.Open(); return "Room Art Lab opened";'
      : command === 'refresh' ? 'UnityEditor.AssetDatabase.Refresh(); return "Room Art Lab refresh requested";' : null;
    const request = code ? { command: 'eval', parameters: { code, timeout: 30000 } }
      : command === 'test' ? { command: 'run_tests', parameters: { mode: 'editor', filter: 'Orionis.RoomArtLab.Tests', filter_type: 'assembly', timeout: 60 } }
      : command === 'cancel-tests' ? { command: 'cancel_tests', parameters: {} } : null;
    if (!request && command !== 'status') throw Error('Use stage, stage-assets, --check, status, refresh, open, test or cancel-tests.');
    const response = await fetch(`http://127.0.0.1:${descriptor.port}${request ? '/api/exec' : '/api/editor_status'}`, {
      method: request ? 'POST' : 'GET', headers: { Authorization: `Bearer ${descriptor.evalToken}`, 'Content-Type': 'application/json' },
      ...(request ? { body: JSON.stringify(request) } : {}), signal: AbortSignal.timeout(65000),
    });
    const result = await response.json();
    console.log(JSON.stringify(result, (key, value) => key.toLowerCase() === 'results' && Array.isArray(value)
      ? value.filter(r => String(r.status ?? r.Status ?? r.result ?? r.Result).toLowerCase() !== 'passed') : value, 2));
    if (!response.ok || result.success === false || result.result?.success === false || result.result?.Summary?.Failed > 0) process.exitCode = 1;
  }
}
